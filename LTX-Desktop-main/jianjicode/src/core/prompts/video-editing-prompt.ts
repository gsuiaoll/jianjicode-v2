/**
 * 构建包含编辑上下文的完整 system prompt。
 * 在基础视频编辑 prompt 之上注入当前编辑状态。
 */
export function buildVideoEditingPrompt(opts?: {
  editContext?: EditContext
  toolList?: string[]
  customInstructions?: string
  templateList?: string[]
}): string {
  const parts: string[] = [VIDEO_EDITING_SYSTEM_PROMPT]

  // 注入可用模板信息
  if (opts?.templateList && opts.templateList.length > 0) {
    const tplLines: string[] = ["\n## 可用视频编辑模板"]
    tplLines.push(
      "以下预设模板可通过 template_manager 工具一键应用，每个模板包含多步编辑操作：",
    )
    for (const desc of opts.templateList) {
      tplLines.push(`- ${desc}`)
    }
    tplLines.push('用户可通过自然语言调用模板，如"用复古风格处理这个视频"。')
    parts.push(tplLines.join("\n"))
  }

  // 注入编辑上下文（当前视频、已应用的操作等）
  if (opts?.editContext) {
    const ctx = opts.editContext
    const ctxLines: string[] = ["\n## 当前编辑状态"]

    if (ctx.currentVideo) {
      ctxLines.push(`- 当前视频：${ctx.currentVideo}`)
    }
    if (ctx.videoInfo) {
      const vi = ctx.videoInfo
      ctxLines.push(
        `- 视频信息：时长=${vi.duration ?? "未知"}, 分辨率=${vi.width ?? "?"}x${vi.height ?? "?"}, 帧率=${vi.fps ?? "?"}`,
      )
    }
    if (ctx.lastOperation) {
      ctxLines.push(`- 上次操作：${ctx.lastOperation}`)
    }
    if (ctx.appliedEffects && ctx.appliedEffects.length > 0) {
      ctxLines.push(`- 已应用效果：${ctx.appliedEffects.join(", ")}`)
    }
    if (ctx.pendingOperations && ctx.pendingOperations.length > 0) {
      ctxLines.push(`- 待执行操作：${ctx.pendingOperations.join(", ")}`)
    }

    parts.push(ctxLines.join("\n"))
  }

  // 注入可用工具列表
  if (opts?.toolList && opts.toolList.length > 0) {
    const toolLines = ["\n## 当前可用工具"]
    for (const desc of opts.toolList) {
      toolLines.push(`- ${desc}`)
    }
    parts.push(toolLines.join("\n"))
  }

  // 自定义指令（最高优先级）
  if (opts?.customInstructions) {
    parts.push(`\n## 特别指示\n${opts.customInstructions}`)
  }

  return parts.join("\n")
}

/**
 * 生成可用工具列表的描述文本。
 * 按分类组织，方便模型理解工具的选择范围。
 */
export function buildToolListSummary(
  descriptions: Array<{ id: string; description: string }>,
): string[] {
  return descriptions.map((t) => `**${t.id}**: ${t.description}`)
}
